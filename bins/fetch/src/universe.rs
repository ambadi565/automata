//! `universe.toml`: the symbols the system may trade or research.

use std::path::Path;

use anyhow::{Context, Result, bail};
use saarthi_core::{Exchange, Symbol};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Universe {
    pub name: String,
    pub exchange: Exchange,
    #[serde(default)]
    pub source: String,
    #[serde(default)]
    pub as_of: String,
    pub symbols: Vec<Symbol>,
}

impl Universe {
    pub fn load(path: &Path) -> Result<Self> {
        let s = std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
        let u: Universe = toml::from_str(&s).with_context(|| format!("parsing {}", path.display()))?;
        u.validate()?;
        Ok(u)
    }

    pub fn validate(&self) -> Result<()> {
        if self.symbols.is_empty() {
            bail!("universe {:?} has no symbols", self.name);
        }
        let mut seen = std::collections::HashSet::new();
        for s in &self.symbols {
            if !seen.insert(s) {
                bail!("duplicate symbol {s} in universe {:?}", self.name);
            }
        }
        Ok(())
    }

    /// Builds a universe from NSE's official index constituent CSV
    /// (niftyindices.com, columns: Company Name, Industry, Symbol, Series, ISIN Code).
    pub fn from_nse_csv(name: &str, csv: &str, as_of: &str) -> Result<Self> {
        let mut lines = csv.lines().filter(|l| !l.trim().is_empty());
        let header = split_csv(lines.next().context("empty CSV")?);
        let col = |n: &str| {
            header
                .iter()
                .position(|h| h.trim().eq_ignore_ascii_case(n))
                .with_context(|| format!("CSV has no {n:?} column"))
        };
        let (sym_i, series_i) = (col("Symbol")?, col("Series")?);
        let mut symbols = Vec::new();
        for line in lines {
            let f = split_csv(line);
            let sym = f.get(sym_i).map(|s| s.trim()).unwrap_or_default();
            let series = f.get(series_i).map(|s| s.trim()).unwrap_or("EQ");
            if !sym.is_empty() {
                symbols.push(Symbol::new(format!("{sym}-{series}")));
            }
        }
        let u = Universe {
            name: name.to_string(),
            exchange: Exchange::Nse,
            source: "NSE index constituent CSV (niftyindices.com)".into(),
            as_of: as_of.to_string(),
            symbols,
        };
        u.validate()?;
        Ok(u)
    }

    pub fn to_toml(&self) -> Result<String> {
        let header = "# Generated by `fetch universe`. Symbols use SmartAPI trading symbols (SYMBOL-EQ).\n";
        Ok(format!("{header}{}", toml::to_string_pretty(self)?))
    }
}

/// Minimal CSV field splitter with double-quote support.
fn split_csv(line: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut quoted = false;
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '"' if quoted && chars.peek() == Some(&'"') => {
                cur.push('"');
                chars.next();
            }
            '"' => quoted = !quoted,
            ',' if !quoted => out.push(std::mem::take(&mut cur)),
            _ => cur.push(c),
        }
    }
    out.push(cur);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shipped_nifty100_universe_is_valid() {
        let p = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../config/universe.toml"));
        let u = Universe::load(p).unwrap();
        assert_eq!(u.exchange, Exchange::Nse);
        assert_eq!(u.symbols.len(), 100);
        assert!(u.symbols.iter().all(|s| s.as_str().ends_with("-EQ")));
    }

    #[test]
    fn parses_nse_csv() {
        let csv = "Company Name,Industry,Symbol,Series,ISIN Code\r\n\
                   \"Mahindra & Mahindra, Ltd.\",Automobile,M&M,EQ,INE101A01026\r\n\
                   Reliance Industries Ltd.,Oil Gas,RELIANCE,EQ,INE002A01018\r\n";
        let u = Universe::from_nse_csv("NIFTY 100", csv, "2026-10-27").unwrap();
        assert_eq!(u.symbols, vec![Symbol::new("M&M-EQ"), Symbol::new("RELIANCE-EQ")]);
        let back: Universe = toml::from_str(&u.to_toml().unwrap()).unwrap();
        assert_eq!(back.symbols.len(), 2);
    }

    #[test]
    fn rejects_duplicates_and_empty() {
        let csv = "Symbol,Series\nA,EQ\nA,EQ\n";
        assert!(Universe::from_nse_csv("x", csv, "").is_err());
        assert!(Universe::from_nse_csv("x", "Symbol,Series\n", "").is_err());
    }
}
